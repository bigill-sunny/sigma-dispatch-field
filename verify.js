'use strict';
const assert=require('node:assert/strict');
const {seed,execute,project}=require('./model');
const {demoAccounts}=require('./accounts');
const account=id=>demoAccounts.find(a=>a.id===Number(id));
const dispatch=account(1001);
const clock=Date.parse('2026-11-24T17:00:00Z');
Date.now=()=>clock;
let state=seed();
const shift=id=>state.requests.find(r=>r.id===id);
const act=(user,action,id,extra)=>{state=execute(state,{action,id,extra},user).state};
assert.deepEqual(['guard','client','admin'].map(role=>demoAccounts.filter(a=>a.role===role).length),[1000,100,3]);
assert.equal(new Set(demoAccounts.map(a=>a.id)).size,1103);
assert.equal(project(state,account(2100)).catalog.sites.length,1);
act(dispatch,'wave',1);
const invited=r=>Object.keys(r.offers).filter(id=>r.offers[id].status==='Invited');
assert(!invited(shift(1)).includes('3001'));
assert(!invited(shift(1)).includes('3019'));
for(const id of invited(shift(1)).slice(0,10)){
  act(account(id),'volunteer',1);
  act(dispatch,'approve',1,Number(id));
  act(account(id),'ack',1);
}
assert.equal(shift(1).assignments.filter(a=>a.ack).length,10);
act(account(3019),'guard-cancel',2);
assert.equal(shift(2).assignments.length,0);
act(dispatch,'wave',2);
const [declined,replacement]=invited(shift(2));
assert(declined&&replacement);
act(account(declined),'decline',2);
act(account(replacement),'volunteer',2);
act(dispatch,'approve',2,Number(replacement));
assert.equal(shift(2).assignments[0].post,'Supervisor');
assert.equal(project(state,account(replacement)).state.requests.find(r=>r.id===2).mine.guard,Number(replacement));
act(account(replacement),'ack',2);
act(account(replacement),'guard-cancel',2);
act(dispatch,'wave',2);
const outstanding=invited(shift(2))[0];
assert(outstanding);
Date.now=()=>clock+6*60000;
assert.throws(()=>act(account(outstanding),'volunteer',2),/active offer/);
act(dispatch,'escalate',2);
assert.equal(shift(2).escalated,true);
assert.equal(shift(2).followUp.owner,dispatch.name);
assert.equal(shift(2).followUp.due,Date.now()+5*60000);
act(account(1002),'escalate',2);
assert.equal(shift(2).followUp.owner,account(1002).name);
assert.equal(project(state,account(2002)).state.requests.find(r=>r.id===2).supervisorGap,1);
console.log('Passed roster, client scope, credential and conflict exclusions, 10 approvals and acknowledgments, supervisor cancellation and replacement, decline, timeout and escalation.');

const subject=shift(1).assignments[0].guard;
function change(user,action,id,extra,fields){state=execute(state,{action,id,extra,fields},user).state;}
Date.now=()=>shift(1).end+60000;
change(dispatch,'review-duty',1,subject,{arrival:'Late',report:'Needs correction',note:'Missing incident timestamp'});
assert.equal(shift(1).assignments[0].review.report,'Needs correction');
assert.throws(()=>change(account(subject),'review-duty',1,subject,{}));
const summary=project(state,account(2001)).state.requests.find(r=>r.id===1);
assert(summary.timeline.some(e=>e.status==='Approved'));
assert(summary.timeline.every(e=>!Object.hasOwn(e,'guard')));
change(account(subject),'unavailable',null,null,{date:'2026-12-04',from:'21:00',endDate:'2026-12-05',to:'06:00'});
const blocked=state.profiles[subject].unavailable[0];
assert.equal(blocked.end-blocked.start,9*3600000);
change(account(2001),'create-request',null,null,{site:'harbor',date:'2026-12-05',time:'01:00',hours:1,count:1,tier:0,source:'Phone',dress:'Black shoes'});
const overnight=state.requests.at(-1);
assert(!project(state,account(subject)).state.requests.some(r=>r.id===overnight.id&&r.canVolunteer));
change(account(subject),'remove-window',blocked.start,null,{});
assert.equal(state.profiles[subject].unavailable.length,0);
console.log('Passed recorded duty review, permission check, client timeline and overnight unavailability.');
